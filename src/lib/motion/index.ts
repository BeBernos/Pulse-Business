const cache = new Map<string, Motion>();

/** Animação do exercício: tabela → palavras-chave → padrão do grupo muscular. */
export function motionFor(name: string, group?: string): Motion {
  const hit = cache.get(name);
  if (hit) return hit;
  const make = TABLE[name] ?? RULES.find(([re]) => re.test(name))?.[1] ?? BY_GROUP[group ?? ""] ?? (() => M.curl({}));
  const m = make();
  cache.set(name, m);
  return m;
}

export const hasOwnMotion = (name: string) => name in TABLE;
